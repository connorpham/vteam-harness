LANGS = ("en", "vi")


class Labels(object):
    """`lang` picks the column headers; anything outside LANGS falls back to
    English and says so, because a half-translated report is worse than one."""

    def __init__(self, lang):
        self.lang = lang if lang in LANGS else "en"
        self.requested = lang
        self.fellback = self.lang != (lang or "en")

    def __call__(self, key, **kw):
        pair = _T.get(key)
        if not pair:
            return key
        text = pair[1] if self.lang == "vi" else pair[0]
        return text.format(**kw) if kw else text

    def h(self, key, **kw):
        """A column header or section title: local first, the international term
        in brackets when they differ."""
        local = self(key, **kw)
        if self.lang == "en":
            return local
        english = _T[key][0].format(**kw) if kw else _T[key][0]
        return local if english == local else "{} ({})".format(local, english)


