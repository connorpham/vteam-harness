def default_out(evd):
    key = os.path.basename(os.path.abspath(evd).rstrip(os.sep))
    return os.path.join(evd, "{}_testcases.xlsx".format(key))


def export(evd, out=None, lang=None, project=None):
    pack = evdpack.read_pack(evd, project=project)
    out = out or default_out(evd)
    out_dir = os.path.dirname(os.path.abspath(out)) or "."
    L = Labels(lang or (project or {}).get("language") or "en")

    wb = Workbook(title="{} — {}".format(pack.key, L("wb_title")), creator="ai-qa")
    build_summary(wb, pack, L, out_dir)
    build_cases(wb, pack, L, out_dir)
    build_defects(wb, pack, L, out_dir)
    build_traceability(wb, pack, L, out_dir)
    build_evidence(wb, pack, L, out_dir)
    build_evidence_images(wb, pack, L, out_dir)

    parent = os.path.dirname(os.path.abspath(out))
    if parent and not os.path.isdir(parent):
        os.makedirs(parent, exist_ok=True)
    wb.save(out)
    return pack, out, L


def _load_project():
    # vteam's ctx exposes Ctx().cfg(key, default) (ai-qa used ctx.load()/ctx.get);
    # project.language drives the workbook's header language, so this must work.
    if ctx is None:
        return {}
    try:
        c = ctx.Ctx()
        return {"name": str(c.cfg("project.name", "") or ""),
                "key": str(c.cfg("project.key", "") or ""),
                "language": str(c.cfg("project.language", "en") or "en")}
    except Exception:
        return {}


def main():
    ap = argparse.ArgumentParser(description="export an evidence pack to .xlsx")
    ap.add_argument("--evd", help="evidence folder, e.g. evd/SHOP-142")
    ap.add_argument("--out", default=None,
                    help="output path (default: <evd>/<TICKET>_testcases.xlsx)")
    ap.add_argument("--lang", default=None, choices=list(LANGS),
                    help="column-header language (default: project.language)")
    ap.add_argument("--strict", action="store_true",
                    help="exit 1 if the pack leaves anything the report needs undeclared")
    ap.add_argument("--selftest", action="store_true", help="prove this exporter can fail")
    args = ap.parse_args()

    if args.selftest:
        return selftest()
    if not args.evd:
        ap.error("--evd is required (or use --selftest)")

    if not os.path.isdir(args.evd):
        print("XLSX: BLOCKED  no such evidence folder: {}".format(args.evd))
        print("  This is a blocked run, not a failed export. Nothing was written.")
        return 2

    project = _load_project()
    try:
        pack, out, L = export(args.evd, args.out, args.lang, project)
    except OSError as exc:
        print("XLSX: BLOCKED  cannot write the workbook: {}".format(exc))
        return 2

    counts = pack.counts
    sev = pack.severity_counts
    print("XLSX: WROTE  {}".format(out))
    print("  {} sheets · {} case(s): {} pass · {} fail · {} blocked · {} defect(s)".format(
        len(SHEET_NAMES), counts["cases"], counts["pass"], counts["fail"],
        counts["blocked"], len(pack.defects)))
    graded = " · ".join("{} {}".format(sev[s], s) for s in SEVERITIES if sev.get(s))
    if graded:
        print("  severity: {}{}".format(graded, " · {} NOT DECLARED".format(sev[NOT_DECLARED])
                                        if sev.get(NOT_DECLARED) else ""))
    if L.fellback:
        print("  ! language {!r} is not translated — headers are in English".format(L.requested))
    if pack.gaps:
        print("  ! {} declared unknown(s), printed in the workbook's section 5:".format(
            len(pack.gaps)))
        for where, what in pack.gaps[:5]:
            print("      {}: {}".format(where, what.split(" — ")[0]))
        if len(pack.gaps) > 5:
            print("      … and {} more".format(len(pack.gaps) - 5))
        if args.strict:
            print("  --strict: the pack is not complete enough to report from.")
            return 1
    return 0


