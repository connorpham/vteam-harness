#!/usr/bin/env python3
"""xlsx_export.py — turn a finished verification into a spreadsheet a manager
can open, filter and forward.

    python3 .vteam/scripts/xlsx_export.py --evd evd/SHOP-142
    python3 .vteam/scripts/xlsx_export.py --evd evd/SHOP-142 --out /tmp/SHOP-142.xlsx
    python3 .vteam/scripts/xlsx_export.py --selftest

The markdown pack is the record. This is the same record in the shape the rest
of the organisation already reads, laid out to the international test
documentation standard so nobody has to be taught how to read it:

    Summary       ISO/IEC/IEEE 29119-3 §8   test status report — the dashboard
    Test Cases    ISO/IEC/IEEE 29119-3 §7   test case specification (IEEE 829 fields)
    Defects       ISO/IEC/IEEE 29119-3 §9   incident report, graded by severity
    Traceability                            requirement -> case -> result -> defect
    Evidence                                every file, and what it shows

Three rules it does not break:

1. **It never invents a value.** A field the pack does not declare prints as
   NOT DECLARED, in muted grey, and is listed again in the summary's "declared
   unknowns" section. A severity guessed at because Major is the usual answer
   would make this file more dangerous than no file.
2. **It adds nothing.** Every cell is traceable to a line in the pack. There is
   no scoring, no weighting and no interpretation of its own.
3. **It says so when the pack contradicts itself** — a verdict that asserts a
   defect with no failed case, a PASS with one.

Exit 0 = written. Exit 1 = written, but `--strict` and the pack has declared
unknowns. Exit 2 = BLOCKED: nothing to export, or nowhere to write it.

Prove it:  python3 xlsx_export.py --selftest

Python 3.9 compatible. No third-party packages, by design.
"""
