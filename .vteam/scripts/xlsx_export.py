def _rewrite(root, rel, fn):
    path = os.path.join(root, rel)
    with open(path, "r", encoding="utf-8") as fh:
        text = fh.read()
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(fn(text))


def _sheet_cells(path, index):
    """One sheet's cells as {"A4": "text"}, read back out of the saved workbook.
    Asserting on the file rather than on the objects that produced it is the
    whole point: a builder can be right while the writer drops the cell."""
    import zipfile
    from xml.etree import ElementTree
    with zipfile.ZipFile(path) as z:
        xml = z.read("xl/worksheets/sheet{}.xml".format(index)).decode("utf-8")
    ns = "{http://schemas.openxmlformats.org/spreadsheetml/2006/main}"
    out = {}
    for c in ElementTree.fromstring(xml).iter(ns + "c"):
        node = c.find(ns + "is/" + ns + "t")
        if node is None:
            node = c.find(ns + "v")
        if node is not None and node.text is not None:
            out[c.get("r")] = node.text
    return out


def _sheet_text(path, index):
    """The visible text of one sheet, in row order."""
    cells = _sheet_cells(path, index)
    return "\n".join(cells[k] for k in sorted(
        cells, key=lambda r: (int(re.sub(r"[A-Z]", "", r)), re.sub(r"\d", "", r))))


def _column(path, index, letter):
    cells = _sheet_cells(path, index)
    return [v for k, v in sorted(cells.items(), key=lambda kv: int(re.sub(r"[A-Z]", "", kv[0])))
            if re.sub(r"\d", "", k) == letter]


