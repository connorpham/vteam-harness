def declared(value, style="cell"):
    """A cell that says NOT DECLARED rather than sitting empty. An empty cell
    reads as "nothing to say here"; this one reads as "nobody said"."""
    text = str(value or "").strip()
    return S(text, style) if text else S(NOT_DECLARED, "muted")


def declared_value(value, style="cell"):
    """EXPECTED and ACTUAL cells. "works as expected" is present and says
    nothing — the reader cannot tell what the screen was supposed to read — so
    it prints as NOT DECLARED, exactly like a missing value, and the gap under
    section 5 says which case wrote it. See docs/qa/method/case-writing.md."""
    text = str(value or "").strip()
    if text and VAGUE_VALUE.match(text):
        return S(NOT_DECLARED, "muted")
    return declared(text, style)


def dash(value, style="cell_center"):
    text = str(value or "").strip()
    return S(text, style) if text else S(DASH, "dash")


def result_style(result):
    return {"PASS": "pass", "FAIL": "fail", "BLOCKED": "blocked"}.get(result, "muted")


def severity_style(severity):
    return {"Blocker": "blocker", "Critical": "critical",
            "Major": "major", "Minor": "minor"}.get(severity, "muted")


def verdict_style(verdict):
    if verdict == "PASS":
        return "pass"
    if verdict in ("FAIL", "NEW-BUG"):
        return "fail"
    if verdict in ("PARTIAL", "UNCLEAR"):
        return "major"
    if verdict == "BLOCKED":
        return "blocked"
    return "muted"


def human_size(n):
    if n < 1024:
        return "{} B".format(n)
    if n < 1024 * 1024:
        return "{:.1f} KB".format(n / 1024.0)
    return "{:.1f} MB".format(n / (1024.0 * 1024.0))


def bar(rate, width=22):
    filled = int(round(width * max(0, min(100, rate)) / 100.0))
    return "█" * filled + "░" * (width - filled)


def bullets(items):
    return "\n".join("• {}".format(i) for i in items)


def numbered(items):
    if not items:
        return ""
    if len(items) == 1 and not re.match(r"^\s*\d+[.)]", items[0]):
        return items[0]
    return "\n".join(re.sub(r"^\s*(\d+)[.)]\s*", r"\1. ", i) for i in items)


def link_for(evidence, out_dir):
    try:
        rel = os.path.relpath(evidence.abs, out_dir)
    except ValueError:
        return None
    return rel.replace(os.sep, "/")


def evidence_summary(case, limit=6):
    names = [e.rel for e in case.evidence if e.rel.split("/")[-1] != "manifest.md"]
    if not names:
        return ""
    shown = names[:limit]
    text = "\n".join(shown)
    if len(names) > len(shown):
        text += "\n… and {} more (see the Evidence sheet)".format(len(names) - len(shown))
    return text


