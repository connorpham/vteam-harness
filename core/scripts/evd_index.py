#!/usr/bin/env python3
"""evd_index.py — make the evidence folder answer its own questions.

Two questions get asked of every evidence folder, usually months later by
somebody who was not there:

    what was actually tested here?      — and —      which case is this file from?

A tree of `TC_1/ TC_2/ TC_3/` answers neither. This writes the answer into
`evd/<TICKET>/manifest.md`, between markers, from the case manifests
themselves — so the index cannot drift from the evidence it describes. The
prose around the block is yours; only the block is regenerated.

    python3 .vteam/scripts/evd_index.py --evd evd/SHOP-142
    python3 .vteam/scripts/evd_index.py --evd evd/SHOP-142 --check   # exit 1 if stale

`evd_check.py` runs the same rendering and reds a manifest whose index no
longer matches the folder — an index that lies is worse than no index.

Prove it:  python3 evd_index.py --selftest
Python 3.9 compatible. No dependencies.
"""
import argparse
import os
import re
import sys

BEGIN = "<!-- vteam:index -->"
END = "<!-- /vteam:index -->"
CASE_DIR = re.compile(r"^TC_(\d+)(?:_(.+))?$")
STEP_IMAGE = re.compile(r"^(?:TC\d+_)?\d{2}_.+\.(?:png|jpg|jpeg)$", re.I)
BOXED = re.compile(r"_boxed\.(?:png|jpg|jpeg)$", re.I)


def read(path):
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as fh:
            return fh.read()
    except Exception:
        return ""


def fields(text):
    """The same 'KEY: value' grammar the evidence gate reads, so a manifest
    that satisfies one is legible to the other."""
    out = {}
    for line in text.splitlines():
        m = re.match(r"^\s*(?:[-*]\s*)?([A-Z][A-Z_-]{1,20}):\s*(.*)$", line)
        if m and m.group(1).upper() not in out:
            out[m.group(1).upper()] = m.group(2).strip()
    return out


def cases(evd):
    """Every TC folder, in numeric order — TC_10 sorts after TC_9, which is
    where a plain sort quietly gets it wrong."""
    found = []
    for d in sorted(os.listdir(evd)) if os.path.isdir(evd) else []:
        m = CASE_DIR.match(d)
        if m and os.path.isdir(os.path.join(evd, d)):
            found.append((int(m.group(1)), m.group(2) or "", d))
    return sorted(found, key=lambda t: t[0])


def humanize(slug):
    return re.sub(r"[_-]+", " ", slug).strip()


def _escape(text):
    """A pipe inside a cell would split the row and silently lose a column."""
    return str(text).replace("|", "\\|").strip()


def title_of(slug, f):
    """What this case is FOR, in one line. TITLE: when the author wrote one —
    the same field the spreadsheet export reads — otherwise the folder name,
    which is why the folder name is required."""
    return f.get("TITLE") or humanize(slug) or "(unnamed — rename the folder TC_<n>_<what_it_proves>)"


def evidence_cell(evd, dirname):
    """Name the artefacts, not the count. 'which file do I open' is the whole
    reason someone is reading an index."""
    d = os.path.join(evd, dirname)
    names = sorted(os.listdir(d)) if os.path.isdir(d) else []
    bits = []
    boxed = [n for n in names if BOXED.search(n)]
    shots = [n for n in names if STEP_IMAGE.match(n) and not BOXED.search(n)]
    if boxed:
        bits.append("[{}]({}/{})".format(boxed[0], dirname, boxed[0]))
        if len(boxed) > 1:
            bits.append("+{} boxed".format(len(boxed) - 1))
    if shots:
        bits.append("{} shot{}".format(len(shots), "s" if len(shots) != 1 else ""))
    for extra in ("journey.mjs", "db_verify.md", "cmd_verify.md", "request.http", "response.json"):
        if extra in names:
            bits.append("[{}]({}/{})".format(extra, dirname, extra))
    return " · ".join(bits) or "—"


def render(evd):
    """The generated block. Deterministic: same folder, same bytes."""
    rows = []
    tally = {"PASS": 0, "FAIL": 0, "BLOCKED": 0, "OTHER": 0}
    for num, slug, dirname in cases(evd):
        f = fields(read(os.path.join(evd, dirname, "manifest.md")))
        result = (f.get("RESULT") or "?").upper()
        tally[result if result in tally else "OTHER"] += 1
        note = ""
        if result == "BLOCKED":
            # A blocked case that does not say why reads as a case nobody tried.
            note = " — {}".format(_escape(f.get("REASON") or f.get("BLOCKED_BY") or "no reason given"))
        rows.append("| **TC_{}** | {} | {} | {}{} | {} |".format(
            num,
            _escape(title_of(slug, f)),
            _escape(f.get("KIND") or "—"),
            result,
            note,
            evidence_cell(evd, dirname),
        ))

    total = sum(tally.values())
    summary = "{} case{} · {} PASS · {} FAIL · {} BLOCKED".format(
        total, "" if total == 1 else "s", tally["PASS"], tally["FAIL"], tally["BLOCKED"])

    out = [BEGIN,
           "<!-- generated by evd_index.py — edit the case manifests, then re-run it -->",
           "",
           "## What was verified",
           "",
           "| case | what it proves | kind | result | evidence |",
           "|---|---|---|---|---|"]
    out += rows or ["| — | *no TC_<n>_<what> folders yet* | — | — | — |"]
    out += ["", summary, END]
    return "\n".join(out) + "\n"


def apply(evd, text=None):
    """Replace the block, keeping every word around it. A manifest with no
    block yet gets one after the title, not at the end — an index below the
    tracker attachments is an index nobody scrolls to."""
    block = render(evd) if text is None else text
    path = os.path.join(evd, "manifest.md")
    cur = read(path)
    if BEGIN in cur and END in cur:
        head, rest = cur.split(BEGIN, 1)
        _, tail = rest.split(END, 1)
        return head + block.rstrip("\n") + tail, path
    if not cur.strip():
        title = os.path.basename(os.path.abspath(evd))
        return "# {} — evidence\n\n{}\n".format(title, block.rstrip("\n")), path
    lines = cur.splitlines()
    at = 1 if lines and lines[0].startswith("#") else 0
    return "\n".join(lines[:at] + ["", block.rstrip("\n"), ""] + lines[at:]) + "\n", path


def write(evd):
    new, path = apply(evd)
    if read(path) == new:
        return False, path
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(new)
    return True, path


def stale(evd):
    """The reason the gate can trust the index: '' when current, else why not."""
    cur = read(os.path.join(evd, "manifest.md"))
    if BEGIN not in cur or END not in cur:
        return "manifest.md carries no index block"
    want = render(evd).strip()
    have = (BEGIN + cur.split(BEGIN, 1)[1].split(END, 1)[0] + END).strip()
    return "" if have == want else "the index no longer matches the case folders"


