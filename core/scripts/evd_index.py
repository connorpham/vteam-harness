def selftest():
    import shutil
    import tempfile
    tmp = tempfile.mkdtemp(prefix="evd-index-")
    try:
        evd = os.path.join(tmp, "SHOP-142")
        for d, man, extra in (
            ("TC_1_save10_applies_to_the_total", "RESULT: PASS\nKIND: acceptance\n", "TC1_01_cart.png"),
            ("TC_2_an_expired_code_is_refused", "RESULT: FAIL\nKIND: boundary\n", "TC2_01_error.png"),
            ("TC_10_the_orders_screen_is_intact", "RESULT: BLOCKED\nKIND: whole-screen\nREASON: no staff account\n", None),
        ):
            os.makedirs(os.path.join(evd, d))
            with open(os.path.join(evd, d, "manifest.md"), "w") as fh:
                fh.write(man)
            if extra:
                open(os.path.join(evd, d, extra), "w").close()
                open(os.path.join(evd, d, extra.replace(".png", "_boxed.png")), "w").close()

        checks = []

        def ck(cond, msg):
            checks.append(cond)
            if not cond:
                print("  x {}".format(msg))

        body = render(evd)
        ck("save10 applies to the total" in body, "the folder name is not used as the case title")
        ck("3 cases · 1 PASS · 1 FAIL · 1 BLOCKED" in body, "the tally is wrong: {!r}".format(body.splitlines()[-2]))
        ck("no staff account" in body, "a BLOCKED case must carry its reason into the index")
        ck(body.index("TC_2") < body.index("TC_10"), "TC_10 sorted before TC_2 — numeric order was not used")
        ck("TC1_01_cart_boxed.png" in body, "the boxed image is not linked")

        ck(stale(evd) != "", "a manifest with no index block must be reported stale")
        changed, path = write(evd)
        ck(changed and os.path.exists(path), "the first write did not create manifest.md")
        ck(read(path).startswith("# SHOP-142 — evidence"), "a created manifest has no title")
        ck(stale(evd) == "", "the index is stale immediately after being written")
        ck(write(evd)[0] is False, "rendering is not deterministic — a second write changed the file")

        # Prose around the block survives; a new case makes it stale again.
        with open(path, "a") as fh:
            fh.write("\n## TRACKER ATTACHMENTS\n- SHOP-142_TC1.png\n")
        os.makedirs(os.path.join(evd, "TC_3_totals_survive_a_reload"))
        with open(os.path.join(evd, "TC_3_totals_survive_a_reload", "manifest.md"), "w") as fh:
            fh.write("RESULT: PASS\nKIND: acceptance\n")
        ck(stale(evd) != "", "a new case folder did not make the index stale")
        write(evd)
        ck("TRACKER ATTACHMENTS" in read(path), "regenerating the block destroyed the prose around it")
        ck("totals survive a reload" in read(path), "the new case never reached the index")
        ck(stale(evd) == "", "still stale after a rewrite")

        # A pipe in a value must not blow a column out of the table.
        with open(os.path.join(evd, "TC_3_totals_survive_a_reload", "manifest.md"), "w") as fh:
            fh.write("RESULT: PASS\nKIND: acceptance\nTITLE: total | subtotal both update\n")
        row = [l for l in render(evd).splitlines() if "TC_3" in l][0]
        cells = len(re.findall(r"(?<!\\)\|", row))
        ck(cells == 6, "a pipe inside a value split the row into {} cells: {!r}".format(cells, row))

        failed = checks.count(False)
        print("EVD-INDEX SELFTEST: {}  ({} checks)".format("PASS" if not failed else "FAIL", len(checks)))
        return 1 if failed else 0
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def main():
    ap = argparse.ArgumentParser(description="write the case index into evd/<TICKET>/manifest.md")
    ap.add_argument("--evd", help="the evidence folder, e.g. evd/SHOP-142")
    ap.add_argument("--check", action="store_true", help="report staleness, write nothing")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args()
    if a.selftest:
        return selftest()
    if not a.evd:
        ap.print_help()
        return 2
    if not os.path.isdir(a.evd):
        print("EVD-INDEX: no such evidence folder: {}".format(a.evd))
        return 2
    if a.check:
        why = stale(a.evd)
        print("EVD-INDEX: STALE — {}\n  unblock: python3 .vteam/scripts/evd_index.py --evd {}".format(why, a.evd)
              if why else "EVD-INDEX: CURRENT  ({})".format(a.evd))
        return 1 if why else 0
    changed, path = write(a.evd)
    print("EVD-INDEX: {}  {}".format("WROTE " if changed else "UNCHANGED", path))
    return 0


if __name__ == "__main__":
    sys.exit(main())
